// Google's hosted mirror of Maven Central is listed before Maven Central:
// Maven Central rate-limits shared addresses (HTTP 429), which fails a build
// outright instead of falling through to the next repository.
pluginManagement {
    repositories {
        google()
        maven("https://maven-central.storage-download.googleapis.com/maven2/")
        mavenCentral()
        gradlePluginPortal()
    }
}
dependencyResolutionManagement {
    repositoriesMode.set(RepositoriesMode.FAIL_ON_PROJECT_REPOS)
    repositories {
        google()
        maven("https://maven-central.storage-download.googleapis.com/maven2/")
        mavenCentral()
    }
}
rootProject.name = "weather-app"
include(":app")
